// Writes src/ui/lib/icons/art.gen.ts from src/ui/lib/icons/manifest.json:
// one eager import.meta.glob listing exactly the manifest's files, so Vite
// copies those and nothing else into a build. Never glob a whole pack — the
// full Clockwork Raven sheet is 8,256 files (docs/plans/pixel-icons.md §4.2).
//
//   npm run icons            regenerate after editing the manifest
//
// tests/icons.test.ts imports renderArtGen and fails when the committed file
// and the manifest disagree, so a forgotten run is caught.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
export const MANIFEST_PATH = join(here, '../src/ui/lib/icons/manifest.json');
export const ART_GEN_PATH = join(here, '../src/ui/lib/icons/art.gen.ts');

/** The glob prefix from src/ui/lib/icons/ to src/assets/. */
export const ASSETS_FROM_ICONS = '../../../assets/';

/** The whole text of art.gen.ts for a manifest (icon name → file under src/assets/). */
export function renderArtGen(manifest) {
  const files = [...new Set(Object.values(manifest))].sort();
  const lines = files.map((f) => `    ${JSON.stringify(ASSETS_FROM_ICONS + f)},`);
  return [
    '// Generated by `npm run icons` (scripts/icons.mjs) from manifest.json: the icon',
    '// files the game uses. Only these are build inputs; the packs are gitignored',
    '// (docs/AUTHORSHIP.md §9), and a file missing on disk is simply absent here,',
    '// so its icon shows the emoji. Do not edit — edit the manifest and rerun.',
    '',
    'export const ART_FILES = import.meta.glob(',
    '  [',
    ...lines,
    '  ],',
    "  { eager: true, query: '?url', import: 'default' },",
    ') as Record<string, string>;',
    '',
  ].join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const manifest = JSON.parse(readFileSync(MANIFEST_PATH, 'utf8'));
  writeFileSync(ART_GEN_PATH, renderArtGen(manifest));
  console.log(`art.gen.ts: ${new Set(Object.values(manifest)).size} files for ${Object.keys(manifest).length} icons`);
}
