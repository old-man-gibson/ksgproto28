// Writes src/ui/lib/enemyArt.gen.ts: one eager import.meta.glob listing exactly
// the enemy portraits some MonsterDef names in `art`. Globbing the whole folder
// made every dev page load request all 2,169 battlers as modules and every
// build copy them, for the 41 the bestiary used (2026-11-01).
//
//   npm run enemy-art        regenerate after naming new art on a monster
//
// tests/content.test.ts imports renderEnemyArtGen and fails when the committed
// file and the monsters disagree, so a forgotten run is caught.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { MONSTERS } from '../src/core/registry';

export const ENEMY_ART_GEN_PATH = fileURLToPath(new URL('../src/ui/lib/enemyArt.gen.ts', import.meta.url));

/** The glob prefix from src/ui/lib/ to the battlers folder. */
const ENEMIES_FROM_LIB = '../../assets/enemies/';

/** Glob syntax: a filename holding one would be read as a pattern and match nothing. */
const GLOB_CHARS = /[*?[\]{}()!+@\\]/;

/** Every art filename the monsters declare, sorted, once each. */
export function declaredEnemyArt(): string[] {
  return [...new Set(Object.values(MONSTERS).flatMap((m) => (m.art ? [m.art] : [])))].sort();
}

/** The whole text of enemyArt.gen.ts for a list of filenames under src/assets/enemies/. */
export function renderEnemyArtGen(files: string[]): string {
  const bad = files.filter((f) => GLOB_CHARS.test(f));
  if (bad.length) throw new Error(`enemy art names with glob characters, rename the files: ${bad.join(', ')}`);
  return [
    '// Generated by `npm run enemy-art` (scripts/enemyArt.ts) from the `art` each',
    '// MonsterDef names. Only these are build inputs; the folder is gitignored',
    '// (docs/AUTHORSHIP.md §9), and a file missing on disk is simply absent here,',
    '// so its monster shows the emoji. Do not edit — name the art and rerun.',
    '',
    'export const ENEMY_ART = import.meta.glob(',
    '  [',
    ...files.map((f) => `    ${JSON.stringify(ENEMIES_FROM_LIB + f)},`),
    '  ],',
    "  { eager: true, query: '?url', import: 'default' },",
    ') as Record<string, string>;',
    '',
  ].join('\n');
}

// Behind a flag rather than a main-module check: the test imports this file,
// and an import must never write.
if (process.argv.includes('--write')) {
  const files = declaredEnemyArt();
  writeFileSync(ENEMY_ART_GEN_PATH, renderEnemyArtGen(files));
  console.log(`enemyArt.gen.ts: ${files.length} files`);
}
